#!/usr/bin/env bash
# Bootstrap on the server (personal-1). Idempotent: it overwrites nothing that exists.
# Runs ON the server:   ssh ... 'bash /opt/vulnradar/deploy/bootstrap-server.sh'
set -euo pipefail

APP=/opt/vulnradar
ENV_PROD="$APP/deploy/.env.prod"
PANOPTICON_ENV=/opt/panopticon/deploy/.env.prod

mkdir -p "$APP/data"

# The active upstream is server state, not repo state: the tar does not carry it
# and the proxy mounts it as a file. If missing (first boot), point at slot a.
if [ ! -f "$APP/deploy/upstream.caddy" ]; then
  printf 'reverse_proxy dashboard-a:8501\n' > "$APP/deploy/upstream.caddy"
  echo "upstream.caddy: created (dashboard-a)"
fi

if [ -f "$ENV_PROD" ]; then
  echo "env.prod: already exists (left untouched)"
else
  SOC_PASSWORD="$(openssl rand -hex 16)"

# Shared LiteLLM virtual key: copied server-side, never printed.
  LITELLM_KEY=""
  if [ -f "$PANOPTICON_ENV" ]; then
    LITELLM_KEY="$(awk -F= '/^AI_API_KEY=/{sub(/^AI_API_KEY=/,""); print; exit}' "$PANOPTICON_ENV" | tr -d '\r')"
  fi

  umask 077
  {
    echo "# generated by deploy/bootstrap-server.sh"
    echo "SOC_USER=soc"
    echo "SOC_PASSWORD=$SOC_PASSWORD"
    echo "LLM_PROVIDER=litellm"
    echo "LLM_MODEL=qwen3.8-flash"
    echo "LITELLM_API_KEY=$LITELLM_KEY"
    echo "SYNC_INTERVAL_MINUTES=15"
    echo "GITHUB_TOKEN="
    echo "SLACK_WEBHOOK_URL="
    echo "ALERT_WEBHOOK_URL="
    echo "TZ=Europe/Madrid"
    echo "# External PostgreSQL (required). Fill this in before the first up."
    echo "DATABASE_URL="
  } > "$ENV_PROD"
  chmod 600 "$ENV_PROD"
  echo "env.prod: created (random SOC_PASSWORD, LITELLM_API_KEY: $([ -n "$LITELLM_KEY" ] && echo copied || echo EMPTY))"
fi

chmod 700 "$APP/deploy" 2>/dev/null || true
chmod 600 "$ENV_PROD"

if ! grep -q '^DATABASE_URL=.\+' "$ENV_PROD"; then
  echo "WARNING: DATABASE_URL is empty — the dashboard will not start without external PostgreSQL"
fi

echo "data: $(du -sh "$APP/data" 2>/dev/null | cut -f1 || echo empty)"
echo "free disk: $(df -h / | awk 'NR==2{print $4}')"
echo "port 8501: $(ss -ltn | grep -c ':8501 ' || true) listener(s) already running"
