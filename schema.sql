-- PostgreSQL schema for Hype vs Reality

CREATE TABLE IF NOT EXISTS cves (
    cve_id TEXT PRIMARY KEY,
    published TEXT,
    last_modified TEXT,
    description TEXT,
    cvss_score DOUBLE PRECISION,
    cvss_vector TEXT,
    cvss_severity TEXT,
    vendor TEXT,
    product TEXT,
    raw_json TEXT,
    synced_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS enrichments (
    cve_id TEXT PRIMARY KEY,
    in_kev INTEGER DEFAULT 0,
    kev_date TEXT,
    ransomware_use INTEGER DEFAULT 0,
    epss DOUBLE PRECISION,
    epss_percentile DOUBLE PRECISION,
    poc_count INTEGER DEFAULT 0,
    media_count INTEGER DEFAULT 0,
    tone_score DOUBLE PRECISION,
    branding INTEGER DEFAULT 0,
    brand_name TEXT,
    wild_confirmation INTEGER DEFAULT 0,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (cve_id) REFERENCES cves(cve_id)
);

-- Additive upgrades for existing installations.
ALTER TABLE cves ADD COLUMN IF NOT EXISTS vendor TEXT;
ALTER TABLE cves ADD COLUMN IF NOT EXISTS product TEXT;
ALTER TABLE cves ADD COLUMN IF NOT EXISTS record_state TEXT DEFAULT 'PUBLISHED';
ALTER TABLE cves ADD COLUMN IF NOT EXISTS cvss_source TEXT;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS github_poc_count INTEGER DEFAULT 0;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS exploitdb_poc_count INTEGER DEFAULT 0;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS validated_poc_count INTEGER DEFAULT 0;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS epss_date TEXT;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS epss_model TEXT;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS kev_checked_at TIMESTAMPTZ;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS tone_method TEXT;
ALTER TABLE enrichments ADD COLUMN IF NOT EXISTS tone_model TEXT;

CREATE TABLE IF NOT EXISTS evidence (
    cve_id TEXT NOT NULL REFERENCES cves(cve_id),
    source TEXT NOT NULL,
    kind TEXT NOT NULL,
    external_id TEXT NOT NULL,
    url TEXT,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    event_date TEXT,
    trusted BOOLEAN NOT NULL DEFAULT false,
    active BOOLEAN NOT NULL DEFAULT true,
    payload TEXT,
    PRIMARY KEY (cve_id, source, kind, external_id)
);
CREATE INDEX IF NOT EXISTS idx_evidence_source ON evidence(source, active);
CREATE TABLE IF NOT EXISTS source_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status TEXT NOT NULL,
    version TEXT,
    details TEXT
);
CREATE INDEX IF NOT EXISTS idx_source_runs_source ON source_runs(source, checked_at DESC);
CREATE TABLE IF NOT EXISTS attention_checks (
    cve_id TEXT PRIMARY KEY REFERENCES cves(cve_id),
    checked_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    next_check_at TIMESTAMPTZ NOT NULL
);

-- A successful empty GitHub result also needs a refresh deadline.
CREATE TABLE IF NOT EXISTS poc_checks (
    cve_id TEXT PRIMARY KEY REFERENCES cves(cve_id),
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_check_at TIMESTAMPTZ NOT NULL,
    successful BOOLEAN NOT NULL
);

-- Press mentions (RSS). The PK (cve_id, url) is the de-duplication guard:
-- media_count only goes up when the URL is new for that CVE.
CREATE TABLE IF NOT EXISTS media_mentions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cve_id TEXT NOT NULL,
    url TEXT NOT NULL,
    title TEXT,
    source TEXT,
    published TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (cve_id, url),
    FOREIGN KEY (cve_id) REFERENCES cves(cve_id)
);
ALTER TABLE media_mentions ADD COLUMN IF NOT EXISTS kind TEXT DEFAULT 'unknown';
ALTER TABLE media_mentions ADD COLUMN IF NOT EXISTS story_key TEXT;
ALTER TABLE media_mentions ADD COLUMN IF NOT EXISTS domain TEXT;
CREATE INDEX IF NOT EXISTS idx_mentions_recent ON media_mentions(cve_id, published) WHERE kind = 'press';

-- Feed URLs already through the LLM rerank. Without this, every cycle re-sends
-- the same entries to the model (RSS rotates slowly) and burns minutes for nothing.
CREATE TABLE IF NOT EXISTS reranked_urls (
    url TEXT PRIMARY KEY,
    reranked_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE reranked_urls ADD COLUMN IF NOT EXISTS extractor_version TEXT;

-- PoC repos with their metrics: the CVE detail page shows them expandable.
CREATE TABLE IF NOT EXISTS pocs (
    cve_id TEXT NOT NULL,
    repo TEXT NOT NULL,
    url TEXT NOT NULL,
    stars INTEGER DEFAULT 0,
    forks INTEGER DEFAULT 0,
    language TEXT,
    pushed_at TEXT,
    created_at TEXT,
    seen_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (cve_id, repo)
);

-- CVEs already through the attention backfill: the runner is resumable and does
-- not repeat work across runs.
CREATE TABLE IF NOT EXISTS attention_backfill (
    cve_id TEXT PRIMARY KEY,
    done_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- UNIQUE(cve_id): a single current score per CVE. Scoring UPSERTs
-- (ON CONFLICT(cve_id) DO UPDATE) instead of accumulating historical rows.
CREATE TABLE IF NOT EXISTS scores (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cve_id TEXT NOT NULL UNIQUE,
    hype DOUBLE PRECISION,
    reality DOUBLE PRECISION,
    category TEXT,
    calculated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (cve_id) REFERENCES cves(cve_id)
);
ALTER TABLE scores ADD COLUMN IF NOT EXISTS input_hash TEXT;
ALTER TABLE scores ADD COLUMN IF NOT EXISTS exploitation_state TEXT DEFAULT 'unknown';
ALTER TABLE scores ADD COLUMN IF NOT EXISTS completeness DOUBLE PRECISION;
ALTER TABLE scores ADD COLUMN IF NOT EXISTS algorithm_version TEXT;

CREATE TABLE IF NOT EXISTS soc_sessions (
    token_hash TEXT PRIMARY KEY,
    credential_key TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_soc_sessions_expiry ON soc_sessions(expires_at);

-- Score time series. `scores` holds only the current one, so a CVE's
-- hype/reality evolution lives here: one row per actual change of value.
CREATE TABLE IF NOT EXISTS score_history (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cve_id TEXT NOT NULL,
    hype DOUBLE PRECISION,
    reality DOUBLE PRECISION,
    category TEXT,
    captured_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (cve_id) REFERENCES cves(cve_id)
);
ALTER TABLE score_history ADD COLUMN IF NOT EXISTS algorithm_version TEXT;
ALTER TABLE score_history ADD COLUMN IF NOT EXISTS input_snapshot TEXT;
ALTER TABLE score_history ADD COLUMN IF NOT EXISTS input_hash TEXT;
ALTER TABLE score_history ADD COLUMN IF NOT EXISTS exploitation_state TEXT;
-- Preserve exact inputs even when a changed source rounds to the same score.
CREATE TABLE IF NOT EXISTS score_evaluations (
    cve_id TEXT NOT NULL REFERENCES cves(cve_id),
    input_hash TEXT NOT NULL,
    algorithm_version TEXT NOT NULL,
    evaluated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    input_snapshot TEXT NOT NULL,
    hype DOUBLE PRECISION NOT NULL,
    reality DOUBLE PRECISION NOT NULL,
    category TEXT NOT NULL,
    PRIMARY KEY(cve_id,input_hash)
);

CREATE INDEX IF NOT EXISTS idx_score_history_cve ON score_history(cve_id, captured_at);

-- Log of sent alerts. UNIQUE(cve_id, channel, rule) is the anti-spam
-- lock: the same alert is not sent twice. Inserted only AFTER a successful POST.
CREATE TABLE IF NOT EXISTS alerts_sent (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cve_id TEXT NOT NULL,
    channel TEXT NOT NULL,
    rule TEXT NOT NULL,
    payload_hash TEXT,
    sent_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(cve_id, channel, rule),
    FOREIGN KEY (cve_id) REFERENCES cves(cve_id)
);

-- Incremental sync state. The watermark is the HEAD SHA of the git mirror.
CREATE TABLE IF NOT EXISTS sync_state (
    key TEXT PRIMARY KEY,
    value TEXT,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Log of the autonomous worker. The agents dashboard reads the latest rows.
CREATE TABLE IF NOT EXISTS agent_events (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    ts TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    agent TEXT NOT NULL,
    event_type TEXT NOT NULL,
    details TEXT,
    status TEXT NOT NULL DEFAULT 'SUCCESS'
);
CREATE INDEX IF NOT EXISTS idx_agent_events_ts ON agent_events(ts DESC);

CREATE TABLE IF NOT EXISTS assets (
    asset_id TEXT PRIMARY KEY,
    name TEXT,
    criticality DOUBLE PRECISION,
    product TEXT,
    environment TEXT,
    owner TEXT
);

CREATE TABLE IF NOT EXISTS cve_assets (
    cve_id TEXT,
    asset_id TEXT,
    adjusted_reality DOUBLE PRECISION,
    PRIMARY KEY (cve_id, asset_id)
);

CREATE INDEX IF NOT EXISTS idx_cves_published ON cves(published);
CREATE INDEX IF NOT EXISTS idx_cves_severity ON cves(cvss_severity);
CREATE INDEX IF NOT EXISTS idx_scores_date ON scores(calculated_at);
CREATE INDEX IF NOT EXISTS idx_scores_hype ON scores(hype DESC);
CREATE INDEX IF NOT EXISTS idx_scores_category ON scores(category);

-- Text search (home search box): full-text over the description and
-- trigrams for the nickname / partial id.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;
CREATE INDEX IF NOT EXISTS idx_cves_fts
    ON cves USING gin (to_tsvector('english', coalesce(description, '')));
CREATE INDEX IF NOT EXISTS idx_enrich_brand_trgm ON enrichments USING gin (brand_name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_cves_id_trgm ON cves USING gin (cve_id gin_trgm_ops);
